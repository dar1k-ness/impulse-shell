#!/usr/bin/env python3
"""Writes crates/qsg/src/emoji_data.rs: the emoji properties QTextEngine::itemize sorts
characters by for its emoji segmenter (Qt 6.12, Unicode 17.0.0), per range of code points.

    tools/gen/emoji/gen.py emoji-data.txt > crates/qsg/src/emoji_data.rs

emoji-data.txt is https://www.unicode.org/Public/17.0.0/ucd/emoji/emoji-data.txt.
"""
import sys
from pathlib import Path

# The first property a character has, in the order QTextEngine::itemize asks for them.
PROPERTIES = ["Emoji_Modifier_Base", "Emoji_Modifier", "Emoji_Presentation", "Emoji"]


def main(path):
    kind = {}
    for line in Path(path).read_text(encoding="utf-8").splitlines():
        body = line.partition("#")[0].strip()
        if not body:
            continue
        span, value = (part.strip() for part in body.split(";"))
        if value not in PROPERTIES:
            continue
        first, _, last = span.partition("..")
        for cp in range(int(first, 16), int(last or first, 16) + 1):
            kind[cp] = min(kind.get(cp, len(PROPERTIES)), PROPERTIES.index(value))
    ranges = []
    for cp in sorted(kind):
        if ranges and ranges[-1][1] == cp - 1 and ranges[-1][2] == kind[cp]:
            ranges[-1][1] = cp
        else:
            ranges.append([cp, cp, kind[cp]])
    out = [
        "// @generated by tools/gen/emoji/gen.py from Unicode 17.0.0 (emoji-data.txt), the data of",
        "// Qt 6.12. Do not edit. (first, last, property): the first a character has of",
        "// 0 Emoji_Modifier_Base, 1 Emoji_Modifier, 2 Emoji_Presentation, 3 Emoji.",
        f"pub(crate) static RANGES: [(u32, u32, u8); {len(ranges)}] = [",
    ]
    for at in range(0, len(ranges), 5):
        row = ", ".join(f"({a:#x}, {b:#x}, {k})" for a, b, k in ranges[at:at + 5])
        out.append(f"    {row},")
    out.append("];")
    print("\n".join(out))


if __name__ == "__main__":
    main(sys.argv[1])
