#!/usr/bin/env python3
"""Generate crates/qml/src/xhr_charset_data.rs: the characters that the ICU of Qt 6.12
reads otherwise than the tables of encoding_rs, in the charsets of more bytes than one.

What ICU reads comes from the test that measures the charsets against it: with
XHR_CHARSET_DUMP it writes, for each charset, every character (one, two, three or four
bytes) that ICU reads otherwise than the table does, without the corrections:

    mkdir -p ~/.cache/ri-gate/target/charsets
    tools/ci/gate --run as-tester env XHR_CHARSET_DUMP=/target/charsets cargo nextest run \\
        --frozen --cargo-profile gate --profile gate -p qml --lib the_converters_of_icu
    tools/gen/charset/gen.py ~/.cache/ri-gate/target/charsets > crates/qml/src/xhr_charset_data.rs

(The test fails on that run when the corrections in the tree are not ICU's; the files are
written all the same.)
"""
import pathlib
import sys

CHARSETS = [
    ("SHIFT_JIS", "ShiftJis"),
    ("EUC_JP", "EucJp"),
    ("BIG5", "Big5"),
    ("BIG5_HKSCS", "Big5Hkscs"),
    ("GBK", "Gbk"),
    ("GB2312", "Gb2312"),
    ("GB18030", "Gb18030"),
    ("EUC_KR", "EucKr"),
    ("WINDOWS_949", "Windows949"),
]


def fixes(path):
    two, more = [], []
    for line in path.read_text().splitlines():
        key, units = line.split("\t")
        units = [int(units[i : i + 4], 16) for i in range(0, len(units), 4)]
        char = "".join(chr(u) for u in units).encode("utf-16", "surrogatepass").decode("utf-16")
        if len(char) != 1:
            sys.exit(f"{path.name}: {key} is not one character in ICU: {units}")
        if len(key) <= 4 and len(units) == 1:
            two.append((int(key, 16), units[0]))
        else:
            more.append((int(key, 16), ord(char)))
    return sorted(two), sorted(more)


def field(name, items, form):
    """A field of the table, laid out as rustfmt lays it out."""
    line = f"    {name}: &[{', '.join(form(item) for item in items)}],"
    if len(line) <= 100:
        return line
    return "\n".join([f"    {name}: &["] + [f"        {form(item)}," for item in items] + ["    ],"])


def main(directory):
    tables = [(name, *fixes(pathlib.Path(directory) / f"{file}.tsv")) for name, file in CHARSETS]
    print("// @generated by tools/gen/charset/gen.py from the ICU of Qt 6.12. Do not edit.")
    print("// The characters ICU's table of a charset has otherwise than the table of encoding_rs:")
    print("// the bytes of a character as one number, and the character. In bytes of the program:")
    for name, two, more in tables:
        size = 4 * len(two) + 8 * len(more)
        print(f"// {name}: {len(two) + len(more)} characters, {size} bytes")
    total = sum(4 * len(two) + 8 * len(more) for _, two, more in tables)
    print(f"// All: {sum(len(t) + len(m) for _, t, m in tables)} characters, {total} bytes")
    print("use crate::xhr_text::Fixes;")
    for name, two, more in tables:
        print(f"\npub(crate) static {name}: Fixes = Fixes {{")
        print(field("two", two, lambda f: f"(0x{f[0]:04X}, 0x{f[1]:04X})"))
        print(field("more", more, lambda f: f"(0x{f[0]:X}, '\\u{{{f[1]:X}}}')"))
        print("};")


if __name__ == "__main__":
    main(sys.argv[1])
