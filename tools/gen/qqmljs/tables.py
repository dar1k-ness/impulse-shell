#!/usr/bin/env python3
"""Turns qlalr's output for qqmljs.g (qqmljsgrammar_p.h, qqmljsgrammar.cpp, qqmljsparser.cpp)
into crates/qml/src/qqmljs/grammar.rs. tools/gen/qqmljs/tables runs qlalr and this.

usage: tables.py QQMLJS_G QLALR_OUT_DIR > grammar.rs
"""
import hashlib, re, sys

g, out = sys.argv[1], sys.argv[2]
h = open(f"{out}/qqmljsgrammar_p.h").read()
c = open(f"{out}/qqmljsgrammar.cpp").read()
sha = hashlib.sha256(open(g, "rb").read()).hexdigest()
print("// Generated by tools/gen/qqmljs/tables from qqmljs.g of Qt 6.12.0 (qlalr); do not edit.")
print("// The tables of Qt's QML and JavaScript parser (QQmlJSGrammar).")
print("#![allow(dead_code)]")
print(f'pub const QQMLJS_G_SHA256: &str = "{sha}";')
enum = re.search(r"enum VariousConstants \{(.*?)\};", h, re.S).group(1)
for name, val in re.findall(r"(\w+) = (-?\d+)", enum):
    print(f"pub const {name}: i32 = {val};")
sp = re.search(r"spell \[\] = \{(.*?)\};", c, re.S).group(1)
items = re.findall(r'"((?:[^"\\]|\\.)*)"|\b0\b', sp)
toks = re.findall(r'"(?:[^"\\]|\\.)*"|\b0\b', sp)
print(f"pub static SPELL: [Option<&str>; {len(toks)}] = [")
for t in toks:
    print("    None," if t == "0" else f"    Some({t}),")
print("];")
for name in ["lhs", "rhs", "action_default", "goto_default", "action_index", "action_info", "action_check"]:
    body = re.search(name + r" \[\] = \{(.*?)\};", c, re.S).group(1)
    nums = [int(x) for x in re.findall(r"-?\d+", body)]
    assert all(-32768 <= n < 32768 for n in nums)
    print(f"pub static {name.upper()}: [i16; {len(nums)}] = [")
    for i in range(0, len(nums), 16):
        print("    " + " ".join(f"{n}," for n in nums[i : i + 16]))
    print("];")
p = open(f"{out}/qqmljsparser.cpp").read()
acts = {int(n) for n in re.findall(r"case (\d+):", p[p.index("switch (r) {"):])}
rules = len(re.findall(r"-?\d+", re.search(r"rhs \[\] = \{(.*?)\};", c, re.S).group(1)))
print("/// Whether the rule has an action in qqmljs.g: without one the value of its first symbol stays.")
print(f"pub static RULE_HAS_ACTION: [bool; {rules}] = [")
for i in range(0, rules, 8):
    print("    " + " ".join(("true," if r in acts else "false,") for r in range(i, min(rules, i + 8))))
print("];")
print("""
pub fn nt_action(state: i32, nt: i32) -> i32 {
    let yyn = ACTION_INDEX[(GOTO_INDEX_OFFSET + state) as usize] as i32 + nt;
    if yyn < 0 || ACTION_CHECK[(GOTO_CHECK_OFFSET + yyn) as usize] as i32 != nt {
        return GOTO_DEFAULT[nt as usize] as i32;
    }
    ACTION_INFO[(GOTO_INFO_OFFSET + yyn) as usize] as i32
}

pub fn t_action(state: i32, token: i32) -> i32 {
    let yyn = ACTION_INDEX[state as usize] as i32 + token;
    if yyn < 0 || ACTION_CHECK[yyn as usize] as i32 != token {
        return -(ACTION_DEFAULT[state as usize] as i32);
    }
    ACTION_INFO[yyn as usize] as i32
}""")
