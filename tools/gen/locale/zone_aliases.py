#!/usr/bin/env python3
"""Generate crates/qml/src/zone_aliases.rs from qtbase 6.12's table of IANA zone id aliases.

Usage: zone_aliases.py qtbase/src/corelib/time/qtimezoneprivate_data_p.h crates/qml/src/zone_aliases.rs
"""
import re
import sys

src = open(sys.argv[1]).read()
table = src[src.index("constexpr AliasData aliasMappingTable[] = {"):]
table = table[:table.index("};")]
pairs = re.findall(r"// (\S+) -> (\S+)", table)
assert len(pairs) == len(re.findall(r"\{\s*\d+,\s*\d+\s*\}", table))
out = ["// @generated by tools/gen/locale/zone_aliases.py from qtbase 6.12 (CLDR) aliasMappingTable. Do not edit.",
       "/// A zone id that CLDR has under another name and that name (QTimeZonePrivate::aliasToIana),",
       "/// in the table's order: by the first, whatever its case.",
       f"pub(crate) static ALIASES: [(&str, &str); {len(pairs)}] = ["]
out += [f'    ("{alias}", "{iana}"),' for alias, iana in pairs]
out.append("];")
open(sys.argv[2], "w").write("\n".join(out) + "\n")
print(len(pairs), "aliases", file=sys.stderr)
