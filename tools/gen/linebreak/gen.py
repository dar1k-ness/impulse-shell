#!/usr/bin/env python3
"""Writes crates/shell/src/line_break_data.rs: what Qt 6.12's line breaker reads of its Unicode
tables (qtbase util/unicode/main.cpp, Unicode 17.0.0), per range of code points.

    tools/gen/linebreak/gen.py DIR > crates/shell/src/line_break_data.rs

DIR holds LineBreak.txt, EastAsianWidth.txt and emoji-data.txt of
https://www.unicode.org/Public/17.0.0/ucd/ (emoji-data.txt is in its emoji/ folder).
"""
import sys
from pathlib import Path

# QUnicodeTables::LineBreakClass, in its order.
CLASSES = """OP CL CP QU QU_Pi QU_Pf QU_19 GL NS EX SY IS PR PO NU AL HL ID IN HY WS_HY HH BA
WS_BA HYBA BB B2 ZW CM WJ H2 H3 JL JV JT RI CB EB EM AK AP AS VI VF ZWJ SA SG SP CR LF
BK""".split()
# initLineBreak: classes Qt folds into another.
FOLDED = {"AI": "AL", "XX": "AL", "NL": "BK", "CJ": "NS"}
INITIAL_QUOTE, FINAL_QUOTE, MARK, EAST_ASIAN, UNASSIGNED_PICTOGRAPHIC = 1, 2, 4, 8, 16
LAST = 0x10FFFF


def records(path):
    """(first, last, value, comment) of every data line."""
    for line in Path(path).read_text(encoding="utf-8").splitlines():
        body, _, comment = line.partition("#")
        if not body.strip():
            continue
        span, value = (field.strip() for field in body.split(";")[:2])
        first, _, last = span.partition("..")
        yield int(first, 16), int(last or first, 16), value, comment.split()


def main(ucd):
    # Unlisted code points are unassigned: AL, but ID or PR in the blocks UAX #14 names.
    cls = [CLASSES.index("AL")] * (LAST + 1)
    for first, last in [(0x3400, 0x4DBF), (0x4E00, 0x9FFF), (0xF900, 0xFAFF), (0x1F000, 0x1F7FF),
                        (0x1F900, 0x1FAFF), (0x1FC00, 0x1FFFD), (0x20000, 0x2FFFD),
                        (0x30000, 0x3FFFD)]:
        cls[first:last + 1] = [CLASSES.index("ID")] * (last - first + 1)
    cls[0x20A0:0x20D0] = [CLASSES.index("PR")] * 0x30
    flags = [0] * (LAST + 1)
    assigned = [False] * (LAST + 1)
    for first, last, value, comment in records(ucd / "LineBreak.txt"):
        category = comment[0]
        flag = {"Pi": INITIAL_QUOTE, "Pf": FINAL_QUOTE, "Mn": MARK, "Mc": MARK}.get(category, 0)
        for cp in range(first, last + 1):
            cls[cp] = CLASSES.index(FOLDED.get(value, value))
            flags[cp] |= flag
            assigned[cp] = category != "Cn"
    for first, last, value, _ in records(ucd / "EastAsianWidth.txt"):
        if value in ("W", "F", "H"):
            for cp in range(first, last + 1):
                flags[cp] |= EAST_ASIAN
    for first, last, value, _ in records(ucd / "emoji-data.txt"):
        if value == "Extended_Pictographic":
            for cp in range(first, last + 1):
                if not assigned[cp]:
                    flags[cp] |= UNASSIGNED_PICTOGRAPHIC

    ranges = []
    for cp in range(LAST + 1):
        if not ranges or ranges[-1][1:] != (cls[cp], flags[cp]):
            ranges.append((cp, cls[cp], flags[cp]))
    out = [
        "// @generated by tools/gen/linebreak/gen.py from Unicode 17.0.0 (LineBreak.txt,",
        "// EastAsianWidth.txt, emoji-data.txt), the data of Qt 6.12. Do not edit.",
        "// (first code point of a range, QUnicodeTables::LineBreakClass, flags): flags are",
        "// 1 initial quote (Pi), 2 final quote (Pf), 4 mark (Mn, Mc), 8 East Asian Width W, F",
        "// or H, 16 unassigned and Extended_Pictographic.",
        f"pub(crate) static RANGES: [(u32, u8, u8); {len(ranges)}] = [",
    ]
    for at in range(0, len(ranges), 6):
        row = ", ".join(f"({cp:#x}, {c}, {f})" for cp, c, f in ranges[at:at + 6])
        out.append(f"    {row},")
    out.append("];")
    print("\n".join(out))


if __name__ == "__main__":
    main(Path(sys.argv[1]))
