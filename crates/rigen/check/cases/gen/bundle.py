#!/usr/bin/env python3
"""Regenerates ../ii_*.js from the ii tree: each case is the real ii source
(JS libraries inlined as IIFE modules following `.import`, QML singleton
functions extracted verbatim) plus a driver from drivers/<name>.js. A case whose
sources have left the tree stays as it was last generated.
Usage: bundle.py [RI_ROOT]  (default: repo qml)"""
import os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, "../../../../../qml"))
OUT = os.path.dirname(HERE)
DECL = re.compile(r"^(?:var|let|const|function|class)\s+([A-Za-z_$][\w$]*)", re.M)
IMP = re.compile(r'^\.import\s+"([^"]+)"\s+as\s+(\w+)\s*$', re.M)


def mod_id(path):
    return "M_" + re.sub(r"\W", "_", os.path.relpath(path, ROOT)[:-3])


def bundle(entry, done, out):
    """Appends `var M_x = (function(){...})()` for entry and its deps."""
    if entry in done:
        return mod_id(entry)
    done.add(entry)
    src = open(entry).read()
    head = []
    for rel, alias in IMP.findall(src):
        dep = os.path.normpath(os.path.join(os.path.dirname(entry), rel))
        head.append(f"var {alias} = {bundle(dep, done, out)};")
    body = IMP.sub("", src).replace(".pragma library", "")
    names = list(dict.fromkeys(DECL.findall(body)))
    exports = ", ".join(f"{n}: {n}" for n in names)
    out.append(f"// {os.path.relpath(entry, ROOT)}\nvar {mod_id(entry)} = (function () {{\n"
               + "\n".join(head) + body + f"\nreturn {{ {exports} }};\n}})();\n")
    return mod_id(entry)


def match_brace(s, i):
    """Index after the `}` matching s[i] == '{' (skips strings, comments, regex-ish)."""
    depth, n = 0, len(s)
    while i < n:
        c = s[i]
        if c in "\"'`":
            q = c; i += 1
            while i < n and s[i] != q:
                i += 2 if s[i] == "\\" else 1
        elif s.startswith("//", i):
            i = s.index("\n", i)
        elif s.startswith("/*", i):
            i = s.index("*/", i) + 1
        elif c == "/" and re.search(r"[(,=:!&|?{};]\s*$", s[max(0, i - 20):i]):
            i += 1
            cls = False
            while i < n and (s[i] != "/" or cls):
                if s[i] == "\\": i += 1
                elif s[i] == "[": cls = True
                elif s[i] == "]": cls = False
                i += 1
        elif c == "{":
            depth += 1
        elif c == "}":
            depth -= 1
            if depth == 0:
                return i + 1
        i += 1
    raise ValueError("unbalanced")


def qml_functions(path):
    """Top-level `function` members of a QML file, type annotations stripped."""
    src = open(path).read()
    fns = []
    for m in re.finditer(r"^    function\s+(\w+)\s*\(([^)]*)\)\s*(:\s*[\w.<>\[\]]+\s*)?\{", src, re.M):
        params = re.sub(r":\s*[\w.<>\[\]|]+", "", m.group(2))
        end = match_brace(src, m.end() - 1)
        fns.append((m.group(1), f"function {m.group(1)}({params}) " + src[m.end() - 1:end]))
    return fns


def main():
    drivers = os.path.join(HERE, "drivers")
    for d in sorted(os.listdir(drivers)):
        name = d[:-4]
        drv = open(os.path.join(drivers, d)).read()
        srcs = re.findall(r"^// @(js|qml) (\S+)(?: (\S+))?", drv, re.M)
        gone = [rel for _, rel, _ in srcs if not os.path.exists(os.path.join(ROOT, rel))]
        if gone:
            print("kept", f"ii_{name}.js", "(no longer in the tree:", ", ".join(gone) + ")")
            continue
        parts = [f"// Generated by gen/bundle.py from ii sources + gen/drivers/{d}; do not edit.\n"]
        done = set()
        for kind, rel, only in srcs:
            p = os.path.join(ROOT, rel)
            if kind == "js":
                bundle(p, done, parts)
            else:
                fns = [f for f in qml_functions(p) if not only or f[0] in only.split(",")]
                alias = os.path.basename(rel)[:-4]
                parts.append(f"// {rel}\nvar {alias} = (function () {{\nvar root;\n"
                             + "\n".join(f for _, f in fns)
                             + "\nroot = { " + ", ".join(f"{n}: {n}" for n, _ in fns) + " };\nreturn root;\n})();\n")
        parts.append("// driver\n" + re.sub(r"^// @(js|qml) .*\n", "", drv, flags=re.M))
        open(os.path.join(OUT, f"ii_{name}.js"), "w").write("\n".join(parts))
        print("wrote", f"ii_{name}.js")


main()
