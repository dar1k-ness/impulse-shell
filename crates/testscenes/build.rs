//! Compile the QML scenes of the shell's tests (`crates/shell/tests/scenes`) with rigen, the
//! way `ricompiled-gen` compiles the shell's tree, into tables of this crate (see src/lib.rs).
use std::fmt::Write;
use std::path::{Path, PathBuf};

fn fail(m: &str) -> ! {
    panic!("testscenes: {m}")
}

fn main() {
    let manifest = Path::new(env!("CARGO_MANIFEST_DIR"));
    let root = manifest
        .join("../shell/tests/scenes")
        .canonicalize()
        .unwrap_or_else(|e| fail(&format!("crates/shell/tests/scenes: {e}")));
    println!("cargo:rerun-if-changed={}", root.display());
    let shell_tree = manifest.join("../../qml");
    println!("cargo:rerun-if-changed={}", shell_tree.display());
    let out = PathBuf::from(std::env::var_os("OUT_DIR").unwrap());
    let dir = out.join("gen");
    let tree = rigen::walk::tree(&root);
    if let Some((key, _)) = tree.js.first() {
        fail(&format!(
            "{key}: a scene is a .qml file; .js files are not compiled here"
        ));
    }
    let mut qml = tree.qml;
    qml.sort();
    let mut stats = rigen::Stats::default();
    let mut files = Vec::new();
    let mut reg = String::from("// @generated by testscenes/build.rs\n");
    let (mut qtab, mut ltab, mut stab) = (String::new(), String::new(), String::new());
    for (i, (key, p)) in qml.iter().enumerate() {
        // A scene loads by its path under the scenes directory, a file of the shell's tree by
        // its path under that tree: one name for both would leave it open which code runs.
        if shell_tree.join(key).exists() {
            fail(&format!(
                "scene {key} has the name of a file of the shell's tree (qml/{key}): rename the scene"
            ));
        }
        let src = std::fs::read_to_string(p).unwrap_or_else(|e| fail(&format!("{key}: {e}")));
        let m = rigen::qml_module(key, &src, p, &root, &mut stats)
            .unwrap_or_else(|e| fail(&format!("rigen: {e}")));
        let name = format!("q{i}.rs");
        let path = dir.join(&name).display().to_string();
        writeln!(reg, "#[path = {path:?}] mod q{i};").unwrap();
        writeln!(qtab, "    ({key:?}, q{i}::ENTRIES),").unwrap();
        writeln!(ltab, "    ({key:?}, q{i}::LAYOUTS),").unwrap();
        writeln!(stab, "    ({key:?}, {:#x}),", rigen::walk::src_hash(&src)).unwrap();
        files.push((name, m));
    }
    // A build without the interpreter cannot run a script that has no compiled code.
    if !stats.unsupported.is_empty() {
        let list: Vec<String> = (stats.unsupported.iter().take(20))
            .map(|(k, u)| format!("{k}: {u}"))
            .collect();
        fail(&format!(
            "{} unsupported constructs:\n{}",
            stats.unsupported.len(),
            list.join("\n")
        ));
    }
    writeln!(
        reg,
        "\n/// The directory the scenes were compiled from.\npub const ROOT: &str = {:?};\n\n/// `(scene, entries)` sorted by scene.\nstatic FILES: &[(&str, &[Entry])] = &[\n{qtab}];\n\n/// `(scene, layouts)` sorted by scene.\nstatic LAYOUT_FILES: &[(&str, &[Layout])] = &[\n{ltab}];\n\n/// `(scene, src_hash of the whole file)` sorted by scene.\nstatic SOURCES: &[(&str, u64)] = &[\n{stab}];",
        root.display().to_string()
    )
    .unwrap();
    files.push(("registry.rs".into(), reg));
    let g = rigen::Generated { files, stats };
    rigen::write(&g, &dir).unwrap();
}
