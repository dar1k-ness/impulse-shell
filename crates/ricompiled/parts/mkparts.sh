#!/bin/bash
# Regenerate the part crates, their dependencies in ../Cargo.toml and their release profile
# overrides in the workspace Cargo.toml: mkparts.sh [PARTS]. PARTS must match `PARTS` in
# crates/ricompiled-gen/build.rs. The parts are independent crates: cargo compiles as many at
# once as its jobserver allows, so peak rustc memory is bounded by `-j` / `CARGO_BUILD_JOBS`.
set -e
N=${1:-32}
cd "$(dirname "$0")"
rm -rf p[0-9]*
for ((i = 0; i < N; i++)); do
    d=$(printf p%02d $i); mkdir $d
    {
        echo "# @generated by mkparts.sh"
        echo '[package]'
        printf 'name = "ricompiled-p%02d"\n' $i
        cat <<'X'
version = "0.1.0"
edition.workspace = true
license.workspace = true
rust-version.workspace = true

[lib]
path = "../part.rs"

[dependencies]
qml = { path = "../../../qml", default-features = false }
ricompiled-gen = { path = "../../../ricompiled-gen" }
ricompiled-rt = { path = "../../../ricompiled-rt" }

[lints]
workspace = true
X
    } > $d/Cargo.toml
done
cd ..
python3 - "$N" <<'P'
import re, sys
n = int(sys.argv[1])
s = open('Cargo.toml').read()
deps = ''.join(f'ricompiled-p{i:02} = {{ path = "parts/p{i:02}" }}\n' for i in range(n))
s = re.sub(r'(ricompiled-gen = [^\n]*\n)(ricompiled-p\d\d = [^\n]*\n)*', lambda m: m.group(1) + deps, s)
open('Cargo.toml', 'w').write(s)
# Each part's release override in the workspace manifest (ricompiled-gen's build.rs checks it).
s = open('../../Cargo.toml').read()
prof = '\n'.join(f'[profile.release.package.ricompiled-p{i:02}]\nopt-level = "s"\n' for i in range(n))
s, k = re.subn(r'(\[profile\.release\.package\.ricompiled-p\d\d\]\nopt-level = "s"\n\n?)+', prof, s)
assert k == 1, 'Cargo.toml: no ricompiled-pNN profile block'
open('../../Cargo.toml', 'w').write(s)
P
