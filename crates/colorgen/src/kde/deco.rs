//! Window-decoration extras of the original's `titlebar_utils`: SierraBreeze(Enhanced) /
//! Klassy titlebar opacity, SierraBreeze button colours, Klassy outline colour and the KWin
//! "darker titlebar" window rule. Every edit is in place (comments and other keys kept) and
//! only to configs that already have the decoration's section; KWin is only asked to
//! reconfigure when something changed and KWin is running.

use super::apply::{Body, Bus, Dirs, Report};
use super::color::{self, Rgb};
use super::config::Options;
use super::kconfig::{Doc, left, write_locked, written};
use super::theme::Theme;

const DARKER_RULE: &str = "Darker Titlebar - generated by kde-material-you-colors, do not rename";

pub fn apply(dirs: &Dirs, theme: &Theme, o: &Options, dark: bool, bus: &dyn Bus, r: &mut Report) {
    let mut reload = false;
    let mut klassy_cache = false;
    if let Some(op) = if dark {
        o.titlebar_opacity_dark
    } else {
        o.titlebar_opacity
    } {
        let op = (op as i64).to_string();
        reload |= edit(dirs, "sierrabreezeenhancedrc", "Windeco", r, |d| {
            d.set("Windeco", "BackgroundOpacity", &op)
        });
        let k = edit(dirs, "klassy/klassyrc", "TitleBarOpacity", r, |d| {
            let a = d.set("TitleBarOpacity", "ActiveTitleBarOpacity", &op);
            d.set("TitleBarOpacity", "InactiveTitleBarOpacity", &op) | a
        });
        klassy_cache |= k;
        reload |= k;
    }
    if o.sierra_breeze_buttons {
        let b = sierra_buttons(theme, dark);
        reload |= edit(dirs, "breezerc", "Windeco", r, |d| {
            b.iter()
                .fold(false, |ch, (k, v)| d.set("Windeco", k, v) | ch)
        });
    }
    if o.klassy_outline {
        let t = theme.material.tokens(dark);
        let tok = |n: &str| color::hex(t.get(n).expect("Material token"));
        let active = tok(if dark { "primaryFixedDim" } else { "primary" });
        let inactive = tok("outlineVariant");
        let g = "WindowOutlineStyle";
        let k = edit(dirs, "klassy/klassyrc", g, r, |d| {
            [
                ("ThinWindowOutlineStyleActive", "WindowOutlineCustomColor"),
                ("ThinWindowOutlineStyleInactive", "WindowOutlineCustomColor"),
                ("ThinWindowOutlineCustomColorActive", active.as_str()),
                ("ThinWindowOutlineCustomColorInactive", inactive.as_str()),
                ("WindowOutlineCustomColorOpacityActive", "100"),
                ("WindowOutlineCustomColorOpacityInactive", "100"),
            ]
            .iter()
            .fold(false, |ch, (k, v)| d.set(g, k, v) | ch)
        });
        klassy_cache |= k;
        reload |= k;
    }
    if let Some(list) = &o.darker_window_list {
        reload |= darker_rule(dirs, theme, list, o.pywal_dark(dark), r);
    }
    if klassy_cache {
        bus.signal(
            "/KlassyDecoration",
            "org.kde.Klassy.Style",
            "updateDecorationColorCache",
            Body::Empty,
        );
    }
    if reload && bus.has_owner("org.kde.KWin") {
        bus.call("org.kde.KWin", "/KWin", "org.kde.KWin", "reconfigure");
    }
}

/// Edits `~/.config/<rel>` when it exists and has `group`; true if it changed.
fn edit(
    dirs: &Dirs,
    rel: &str,
    group: &str,
    r: &mut Report,
    f: impl FnOnce(&mut Doc) -> bool,
) -> bool {
    let path = dirs.config.join(rel);
    if !path.is_file() {
        return false;
    }
    let mut d = match Doc::edit(&path) {
        Ok(d) => d,
        Err(e) => {
            left(&path, &e);
            return false;
        }
    };
    if !d.has_group(group) || !f(&mut d) || !written(&path, d.save()) {
        return false;
    }
    if !r.written.contains(&path) {
        r.written.push(path);
    }
    true
}

fn sierra_buttons(theme: &Theme, dark: bool) -> Vec<(&'static str, String)> {
    let m = &theme.material;
    let p = &m.palettes[0];
    let t = m.tokens(dark);
    let tok = |n: &str| t.get(n).expect("Material token");
    let fixed = |c: &str| color::parse(c).expect("colour");
    let (active, inactive) = (tok("onBackground"), tok("surfaceContainerHighest"));
    let a = |c: Rgb| {
        if dark {
            color::blend(active, c, 0.7)
        } else {
            color::blend(c, active, 0.05)
        }
    };
    let s = |c: Rgb| color::triple(c);
    let (close, min, max) = if dark {
        (p[80], p[70], p[70])
    } else {
        (p[50], p[60], p[70])
    };
    let off = s(color::blend(inactive, tok("secondary"), 0.32));
    let mut v = vec![
        ("ButtonCloseActiveColor", s(a(close))),
        ("ButtonMaximizeActiveColor", s(a(max))),
        ("ButtonMinimizeActiveColor", s(a(min))),
        ("ButtonKeepAboveActiveColor", s(a(fixed("#118cff")))),
        ("ButtonKeepBelowActiveColor", s(a(fixed("#5d00b9")))),
        ("ButtonOnAllDesktopsActiveColor", s(a(fixed("#00b9b9")))),
        ("ButtonShadeActiveColor", s(a(fixed("#b900b6")))),
    ];
    for k in [
        "ButtonCloseInactiveColor",
        "ButtonMaximizeInactiveColor",
        "ButtonMinimizeInactiveColor",
        "ButtonKeepAboveInactiveColor",
        "ButtonKeepBelowInactiveColor",
        "ButtonOnAllDesktopsInactiveColor",
        "ButtonShadeInactiveColor",
    ] {
        v.push((k, off.clone()));
    }
    v
}

/// KWin rule colouring the titlebars of `list` (space separated window classes) with a copy of
/// the scheme whose header is the terminal background. KWin only re-reads a rule's scheme when
/// its name changes, so the rule alternates between `…_darker_titlebar` and `…_darker_titlebar2`.
fn darker_rule(dirs: &Dirs, theme: &Theme, list: &str, dark: bool, r: &mut Report) -> bool {
    let base = if dark {
        "MaterialYouDark"
    } else {
        "MaterialYouLight"
    };
    let path = dirs.config.join("kwinrulesrc");
    let mut d = match Doc::edit(&path) {
        Ok(d) => d,
        Err(e) => {
            left(&path, &e);
            return false;
        }
    };
    let mut rules: Vec<String> = d
        .get("General", "rules")
        .map(|v| {
            v.split(',')
                .filter(|s| !s.is_empty())
                .map(String::from)
                .collect()
        })
        .unwrap_or_default();
    let id = match rules
        .iter()
        .find(|id| d.get(id, "Description") == Some(DARKER_RULE))
    {
        Some(id) => id.clone(),
        None => {
            let mut n = rules.len() + 1;
            while rules.contains(&n.to_string()) || d.has_group(&n.to_string()) {
                n += 1;
            }
            let id = n.to_string();
            rules.push(id.clone());
            d.set("General", "count", &rules.len().to_string());
            id
        }
    };
    let first = format!("{base}_darker_titlebar");
    let scheme = if d.get(&id, "decocolor") == Some(first.as_str()) {
        format!("{first}2")
    } else {
        first
    };
    let mut header = Doc::parse(theme.plasma(dark));
    let bg = color::hex(theme.konsole(dark).background);
    header.set("Colors:Header][Inactive", "BackgroundNormal", &bg);
    header.set("Colors:Header", "BackgroundNormal", &bg);
    let mode = if dark { "Dark" } else { "Light" };
    let two = if scheme.ends_with('2') { "2" } else { "" };
    header.set(
        "General",
        "Name",
        &format!("Material You {mode} (darker titlebar{two})"),
    );
    let file = dirs
        .data
        .join("color-schemes")
        .join(format!("{scheme}.colors"));
    if written(&file, write_locked(&file, &header.bytes())) {
        r.written.push(file);
    }
    d.set(&id, "Description", DARKER_RULE);
    d.set(&id, "decocolor", &scheme);
    d.set(&id, "decocolorrule", "2");
    d.set(&id, "wmclassmatch", "3");
    d.set(&id, "wmclass", &format!("({})", list.replace(' ', "|")));
    d.set("General", "rules", &rules.join(","));
    let changed = written(&path, d.save());
    if changed {
        r.written.push(path);
    }
    changed
}
