#!/usr/bin/env python3
"""Reference vectors for the unit tests in crates/colorgen/src/mdc.rs, from materialyoucolor 2.0.10
(https://pypi.org/project/materialyoucolor/2.0.10/), the library generate_colors_material.py uses.

Usage: python3 -m venv v && v/bin/pip install materialyoucolor==2.0.10 && v/bin/python gen.py > vectors.txt
"""
from importlib.metadata import version

from materialyoucolor.contrast.contrast import Contrast
from materialyoucolor.dislike.dislike_analyzer import DislikeAnalyzer
from materialyoucolor.dynamiccolor.dynamic_color import DynamicColor
from materialyoucolor.dynamiccolor.material_dynamic_colors import MaterialDynamicColors as M
from materialyoucolor.hct import Hct
from materialyoucolor.palettes.tonal_palette import TonalPalette
from materialyoucolor.scheme.scheme_content import SchemeContent
from materialyoucolor.scheme.scheme_expressive import SchemeExpressive
from materialyoucolor.scheme.scheme_fidelity import SchemeFidelity
from materialyoucolor.scheme.scheme_fruit_salad import SchemeFruitSalad
from materialyoucolor.scheme.scheme_monochrome import SchemeMonochrome
from materialyoucolor.scheme.scheme_neutral import SchemeNeutral
from materialyoucolor.scheme.scheme_rainbow import SchemeRainbow
from materialyoucolor.scheme.scheme_tonal_spot import SchemeTonalSpot
from materialyoucolor.scheme.scheme_vibrant import SchemeVibrant

assert version("materialyoucolor") == "2.0.10", version("materialyoucolor")

SCHEMES = {
    "Monochrome": SchemeMonochrome,
    "Neutral": SchemeNeutral,
    "TonalSpot": SchemeTonalSpot,
    "Vibrant": SchemeVibrant,
    "Expressive": SchemeExpressive,
    "Fidelity": SchemeFidelity,
    "Content": SchemeContent,
    "Rainbow": SchemeRainbow,
    "FruitSalad": SchemeFruitSalad,
}
# Google blue, a disliked bile yellow (DislikeAnalyzer test colour), pure green.
SEEDS = [0xFF4285F4, 0xFFB08E00, 0xFF00FF00]
LEVELS = [-1.0, -0.5, 0.0, 0.5, 1.0]
# generate_colors_material.py iterates vars(MaterialDynamicColors) and keeps the DynamicColors.
TOKENS = [k for k, v in vars(M).items() if type(v).__name__ == "DynamicColor"]

print("# materialyoucolor", version("materialyoucolor"), "- generated by gen.py, do not edit")
print("tokens", *TOKENS)
for name, cls in SCHEMES.items():
    for seed in SEEDS:
        for dark in (False, True):
            for level in LEVELS:
                s = cls(Hct.from_int(seed), dark, level)
                argbs = (getattr(M, t).get_argb(s) & 0xFFFFFF for t in TOKENS)
                print("scheme", name, f"{seed:08X}", int(dark), repr(level), "".join(f"{a:06X}" for a in argbs))

for hue in range(0, 360, 15):
    for chroma in (0.0, 3.0, 8.0, 16.0, 24.0, 36.0, 48.0, 60.0, 84.0, 120.0, 200.0):
        print("key", repr(float(hue)), repr(chroma), repr(TonalPalette.from_hue_and_chroma(float(hue), chroma).key_color.tone))

TONES = [-10.0, 0.0, 2.5] + [float(t) for t in range(10, 101, 10)] + [49.5, 50.4, 55.0, 59.6, 99.9, 110.0]
RATIOS = [1.0, 1.5, 3.0, 4.5, 7.0, 11.0, 21.0]
PAIR_TONES = [-10.0, 0.0, 10.0, 25.0, 40.0, 49.5, 55.0, 59.6, 70.0, 85.0, 100.0, 110.0]
for a in PAIR_TONES:
    for b in PAIR_TONES:
        print("contrast ratio_of_tones", repr(a), repr(b), repr(Contrast.ratio_of_tones(a, b)))
for fn, f in (
    ("lighter", Contrast.lighter),
    ("darker", Contrast.darker),
    ("lighter_unsafe", Contrast.lighter_unsafe),
    ("darker_unsafe", Contrast.darker_unsafe),
    ("foreground_tone", DynamicColor.foreground_tone),
):
    for t in TONES:
        for r in RATIOS:
            print("contrast", fn, repr(t), repr(r), repr(float(f(t, r))))

for hue in range(80, 125, 5):
    for chroma in (10.0, 16.0, 17.0, 30.0):
        for tone in (40.0, 64.0, 65.0, 66.0, 70.0):
            h = Hct.from_hct(float(hue), chroma, tone)
            print("dislike", f"{h.to_int() & 0xFFFFFF:06X}", f"{DislikeAnalyzer.fix_if_disliked(h).to_int() & 0xFFFFFF:06X}")
